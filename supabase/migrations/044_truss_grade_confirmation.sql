-- =============================================
-- Truss App - 学年の本人確認（年度ごと）
-- =============================================
-- 背景:
-- - 2026年3月頃の登録案内で、前年度の学年を書いた会員が混ざった。
-- - そもそも学年は毎年4月に古くなるため、年度ごとに本人へ確認してもらう仕組みにする。
--
-- 仕組み:
-- - grade_confirmed_for = 本人が学年を確認した年度（4月始まりの西暦。例: 2026）。
-- - ホーム画面は「grade_confirmed_for が現在年度より小さい（または NULL）」の会員に
--   確認ナッジを出す。[合っています] または学年の選び直しで現在年度が入る。
-- - 初期登録時は登録した年度が入る（登録直後にナッジを出さない）。
-- - 既存会員は NULL のため、全員に一巡ナッジが出る（今回の混在の解消を兼ねる）。

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS grade_confirmed_for INTEGER;

COMMENT ON COLUMN public.users.grade_confirmed_for IS
  '学年を本人確認した年度（4月始まり西暦）。現在年度より小さい/NULL の会員にはホームで確認ナッジを表示';
