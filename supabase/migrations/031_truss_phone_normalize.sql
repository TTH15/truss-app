-- =============================================
-- Truss App - 電話番号の表記統一（ハイフンなし）
-- =============================================
-- 目的:
-- - users.phone にハイフンあり/なしが混在しているため、数字のみ（先頭 + は保持）に統一する
-- - 全角数字・全角ハイフン・空白・括弧などの区切り文字も除去する
-- - アプリ側も保存時に同じ正規化（packages/core/src/phone.ts の normalizePhone）を行うため、
--   本マイグレーション以降は混在が発生しない

UPDATE public.users
SET phone = regexp_replace(
  translate(phone, '０１２３４５６７８９＋', '0123456789+'),
  '[^0-9+]', '', 'g'
)
WHERE phone <> regexp_replace(
  translate(phone, '０１２３４５６７８９＋', '0123456789+'),
  '[^0-9+]', '', 'g'
);
